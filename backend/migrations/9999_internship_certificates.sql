CREATE TABLE IF NOT EXISTS internship_certificate_templates (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 mime_type TEXT NOT NULL DEFAULT 'application/pdf',
 pdf_data BYTEA NOT NULL,
 uploaded_by UUID,
 uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS internship_certificates (
 id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
 allocation_id UUID NOT NULL REFERENCES batch_allocations(id),
 certificate_number TEXT NOT NULL UNIQUE,
 student_name TEXT NOT NULL,
 college_name TEXT,
 batch_name TEXT,
 project_title TEXT,
 start_date DATE NOT NULL,
 end_date DATE NOT NULL,
 chairman_name TEXT NOT NULL DEFAULT 'PRASAD K',
 ceo_name TEXT NOT NULL DEFAULT 'SRINIVASA RAO K',
 status TEXT NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','ISSUED','REVOKED')),
 issued_at TIMESTAMPTZ,
 issued_by UUID,
 template_id INTEGER REFERENCES internship_certificate_templates(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS one_active_certificate_per_allocation ON internship_certificates(allocation_id) WHERE status <> 'REVOKED';

CREATE TABLE IF NOT EXISTS internship_certificate_fonts (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 font_data BYTEA NOT NULL,
 uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
