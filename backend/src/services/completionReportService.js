import PDFDocument from "pdfkit";
import { writeStoredBuffer } from "../common/storage/storage.service.js";
export function generateCompletionReport(d) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 48 }),
      chunks = [];
    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("error", reject);
    doc.on("end", async () => {
      try {
        resolve(
          await writeStoredBuffer(Buffer.concat(chunks), {
            prefix: "completion-reports",
            filename: "completion-" + d.internId + ".pdf",
            contentType: "application/pdf",
          }),
        );
      } catch (error) {
        reject(error);
      }
    });
    doc
      .font("Helvetica-Bold")
      .fontSize(20)
      .text("GAINT CLOUT TECHNOLOGIES PVT. LTD.", { align: "center" })
      .moveDown(0.3)
      .fontSize(18)
      .text("COLLEGE INTERNSHIP COMPLETION REPORT", { align: "center" })
      .moveDown();
    const row = (a, b) => {
      doc
        .font("Helvetica-Bold")
        .fontSize(11)
        .text(a + ": ", { continued: true })
        .font("Helvetica")
        .text(String(b ?? "—"))
        .moveDown(0.35);
    };
    row("Student", d.name);
    row("Roll Number", d.roll);
    row("College", d.college);
    row("Program / Branch", [d.program, d.branch].filter(Boolean).join(" / "));
    row("Batch", d.batch);
    row("Domain", d.domain);
    row("Internship Period", d.period);
    row("Allotment / Permission Reference", d.allotmentReference);
    row("Attendance", d.attendancePercent + "%");
    doc
      .moveDown()
      .font("Helvetica-Bold")
      .fontSize(13)
      .text("Performance Summary")
      .moveDown(0.4);
    row("Average Task Marks", d.taskAvg);
    row("Average Fortnight Individual Marks", d.reviewAvg);
    row("Final Group Marks", d.groupMarks);
    row("Final Individual Marks", d.individualMarks);
    row("Final Recommendation", d.recommendation);
    doc
      .moveDown()
      .font("Helvetica-Bold")
      .fontSize(13)
      .text("Mentor Remarks")
      .moveDown(0.4)
      .font("Helvetica")
      .fontSize(11)
      .text(d.mentorRemarks || "—");
    doc
      .moveDown(2)
      .fontSize(10)
      .text(
        "Generated by GAINT Intern Management System · " +
          new Date().toLocaleString("en-IN"),
        { align: "center" },
      );
    doc.end();
  });
}
